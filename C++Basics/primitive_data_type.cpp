// PRIMITIVE DATA TYPES IN C++ :- Boolean, Char, Float, Int, Double
#include <iostream>
using namespace std;
int main() {

    // BOOLEAN = 1 byte
    bool isSafe  = true;
    cout<< isSafe<< endl;

    // CHAR = 1 byte
    char grade = 'A';
    cout<< grade<<endl;

    // FLOAT = 4 byte
    float PI = 3.14f;
    cout << PI << endl;

    // INT = 4 byte
    int age = 22;
    cout << age << endl;

    // DOUBLE = 8 byte (default data type)
    double largeDecimalNumbers = 3.14159265358979323846;
    cout << largeDecimalNumbers << endl;

    return 0;
}




